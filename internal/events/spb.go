// Package events — генерация событий СПб для финального .ics.
package events

import (
	"sort"

	"github.com/thegalkin/spb-fireworks-ics/internal/calendar"
	"github.com/thegalkin/spb-fireworks-ics/internal/ical"
	"time"
)

// SPbFireworks — все фиксированные праздники Санкт-Петербурга с салютами
// и крупными городскими событиями.
//
// Большая часть дат — федеральные (Новый год, 9 Мая, 12 Июня, 4 Ноября),
// поэтому они дублируют данные из upstream-календаря. Но upstream может
// перенести выходной, а сам праздник / салют — нет. Поэтому СПб-события
// мы всегда добавляем сами из правил, а upstream используем ТОЛЬКО как
// источник неявной информации о переносах рабочих дней (чтобы в финальном
// .ics салют НЕ оказался случайно «отменён» переносом).
func SPbFireworks(year int) []ical.Event {
	loc, _ := time.LoadLocation("Europe/Moscow")
	at := func(m time.Month, d, hh, mm int) time.Time {
		return time.Date(year, m, d, hh, mm, 0, 0, loc)
	}
	id := func(slug string) string { return "spb-" + slug + "-2026@spb-fireworks-ics" }

	var out []ical.Event
	add := func(summary, desc, where string, t time.Time, durMin int, allDay bool, slug string) {
		end := t
		if !allDay {
			end = t.Add(time.Duration(durMin) * time.Minute)
		} else {
			end = at(t.Month(), t.Day()+1, 0, 0)
		}
		out = append(out, ical.Event{
			UID:         id(slug),
			Start:       t,
			End:         end,
			AllDay:      allDay,
			Summary:     summary,
			Description: desc,
			Location:    where,
		})
	}

	// 27 января — годовщина полного снятия блокады Ленинграда (1944).
	// Салют у Петропавловской крепости в 21:00.
	add("Салют: годовщина снятия блокады Ленинграда",
		"Артиллерийский салют у стен Петропавловской крепости (30 залпов). Бесплатно.",
		"Пляж Петропавловской крепости, Санкт-Петербург",
		at(time.January, 27, 21, 0), 15, false, "blokada")

	// 23 февраля — День защитника Отечества. Салют 21:00.
	add("Салют: День защитника Отечества",
		"Праздничный салют у Петропавловской крепости.",
		"Пляж Петропавловской крепости, Санкт-Петербург",
		at(time.February, 23, 21, 0), 15, false, "feb23")

	// 8 марта — государственный праздник, выходной.
	add("Международный женский день",
		"Государственный праздник. Выходной.",
		"Россия",
		at(time.March, 8, 0, 0), 0, true, "mar8")

	// 9 мая — День Победы, главный салют Петербурга в 22:00.
	add("Салют: День Победы",
		"Главный салют Санкт-Петербурга. 22:00 у стен Петропавловской крепости. "+
			"Артиллерийские залпы и фейерверк.",
		"Пляж Петропавловской крепости, Санкт-Петербург",
		at(time.May, 9, 22, 0), 20, false, "may9")

	// 27 мая — День города Санкт-Петербурга (день основания, 1703).
	add("Салют: День города Санкт-Петербурга",
		"Главный городской праздник. Салют на Петропавловской крепости в 23:55. "+
			"Концерты, гуляния, развод мостов.",
		"Дворцовая площадь, Санкт-Петербург",
		at(time.May, 27, 23, 55), 15, false, "den-goroda-salyut")

	add("День города Санкт-Петербурга — дневная программа",
		"Парад, концерты, ярмарки по всему городу. Бесплатно.",
		"Санкт-Петербург",
		at(time.May, 27, 0, 0), 0, true, "den-goroda-day")

	// 12 июня — День России. Салют 22:00.
	add("Салют: День России",
		"Праздничный салют у Петропавловской крепости.",
		"Пляж Петропавловской крепости, Санкт-Петербург",
		at(time.June, 12, 22, 0), 15, false, "den-rossii-salyut")

	add("День России",
		"Государственный праздник. Выходной.",
		"Россия",
		at(time.June, 12, 0, 0), 0, true, "den-rossii-day")

	// Алые паруса — последняя суббота июня (ночь выпускников).
	ap := calendar.LastSaturdayOfJune(year)
	add("Алые паруса — генеральная репетиция",
		"Ночные проходы брига «Россия» по Неве с подсветкой парусов. "+
			"Бесплатно, видно с центральных набережных.",
		"Набережные Невы, Санкт-Петербург",
		ap.AddDate(0, 0, -1).Add(22*time.Hour), 180, false, "alye-parusa-rep")

	add("Алые паруса — ночь выпускников",
		"Главный городской праздник. Концерт на Дворцовой площади (закрытая зона, "+
			"по приглашениям), затем водно-пиротехническое шоу с бригом «Россия» под "+
			"алыми парусами и фейерверк в 00:40–01:10.",
		"Дворцовая площадь + Нева, Санкт-Петербург",
		ap.Add(20*time.Hour), 360, false, "alye-parusa")

	// День ВМФ — последнее воскресенье июля (с 2025 года; ФЗ-419 от 25.12.2023).
	vmf := calendar.LastSundayOfJuly(year)
	add("День ВМФ — дневная программа",
		"Главный военно-морской парад страны: проход кораблей, подводных лодок и "+
			"авиации по Неве от Финского залива. Открытые мероприятия в Кронштадте.",
		"Нева, Санкт-Петербург и Кронштадт",
		vmf, 0, true, "vmf-day")

	add("Салют: День Военно-Морского флота",
		"Праздничный салют у стен Петропавловской крепости, ~22:00.",
		"Пляж Петропавловской крепости, Санкт-Петербург",
		at(vmf.Month(), vmf.Day(), 22, 0), 15, false, "vmf-salyut")

	// 4 ноября — День народного единства.
	add("День народного единства",
		"Государственный праздник. Выходной.",
		"Россия",
		at(time.November, 4, 0, 0), 0, true, "nov4")

	sort.Slice(out, func(i, j int) bool {
		return out[i].Start.Before(out[j].Start)
	})
	return out
}
